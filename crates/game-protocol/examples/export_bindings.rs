use std::{fs, path::PathBuf};

use shinobi_game_protocol::{ClientMessage, PROTOCOL_VERSION, ServerMessage, TileCoordinateDto};
use ts_rs::{Config, TS};

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let output_directory =
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../packages/protocol/src/generated");
    fs::create_dir_all(&output_directory)?;
    let config = Config::default();
    let tile_coordinate = TileCoordinateDto::decl(&config);
    let client_message = ClientMessage::decl(&config);
    let server_message = ServerMessage::decl(&config);

    let bindings = format!(
        "// @generated by shinobi-game-protocol. Do not edit by hand.\n\nexport const PROTOCOL_VERSION = {PROTOCOL_VERSION:?} as const;\n\nexport {tile_coordinate}\n\nexport {client_message}\n\nexport {server_message}\n",
    );

    fs::write(output_directory.join("bindings.ts"), bindings)?;
    Ok(())
}
